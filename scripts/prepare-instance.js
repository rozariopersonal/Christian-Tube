const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const args = process.argv.slice(2);
let instanceId = 'christian_tube';
let channel = 'prod';

for (let i = 0; i < args.length; i++) {
  const arg = args[i];
  if (arg === '--channel' && args[i + 1]) {
    channel = args[++i].toLowerCase();
  } else if (arg.startsWith('--channel=')) {
    channel = arg.split('=')[1].toLowerCase();
  } else if (arg === 'beta' || arg === 'prod') {
    channel = arg;
  } else if (!arg.startsWith('--')) {
    instanceId = arg;
  }
}

const isBeta = channel === 'beta';
const rootDir = path.resolve(__dirname, '..');
const instanceDir = path.join(rootDir, 'instances', instanceId);

if (!fs.existsSync(instanceDir)) {
  console.error(`Error: Instance directory '${instanceDir}' does not exist!`);
  process.exit(1);
}

const configPath = path.join(instanceDir, 'config.json');
if (!fs.existsSync(configPath)) {
  console.error(`Error: Config file '${configPath}' not found!`);
  process.exit(1);
}

const config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
if (isBeta) {
  config.isBeta = true;
  config.channel = 'beta';
  config.applicationId = `${config.applicationId}.beta`;
  config.appName = `${config.appName} Beta`;
  config.apkFileName = config.apkFileName.replace(/\.apk$/, '-beta.apk');
} else {
  config.isBeta = false;
  config.channel = 'prod';
}

console.log(`🚀 Preparing PrivateTube engine for instance: ${config.appName} (${config.instanceId}) [Channel: ${channel.toUpperCase()}]...`);

// 1. Write instance config to mobile assets
const mobileAssetsDir = path.join(rootDir, 'apps', 'mobile', 'assets');
fs.mkdirSync(mobileAssetsDir, { recursive: true });
fs.writeFileSync(path.join(mobileAssetsDir, 'app_config.json'), JSON.stringify(config, null, 2), 'utf8');
console.log(`✅ Synced app_config.json to mobile assets (${isBeta ? 'Beta' : 'Production'})`);

// 2. Prepare instance icons (with dynamic BETA badge overlay if in beta channel)
const iconSrc = path.join(instanceDir, 'assets', 'icon.png');
if (fs.existsSync(iconSrc)) {
  const resDir = path.join(rootDir, 'apps', 'mobile', 'android', 'app', 'src', 'main', 'res');
  const logoTarget = path.join(mobileAssetsDir, 'logo.png');
  const iconScript = path.join(rootDir, 'scripts', 'generate-icons.py');
  try {
    const pythonCmd = process.platform === 'win32' ? 'python' : 'python3';
    execSync(`"${pythonCmd}" "${iconScript}" "${iconSrc}" "${resDir}" "${logoTarget}" "${isBeta ? 'true' : 'false'}"`, { stdio: 'inherit' });
    console.log(`✅ Generated resized Android launcher icons (48x48 to 192x192)${isBeta ? ' with BETA badge' : ''}`);
    console.log(`✅ Synced logo.png to mobile assets${isBeta ? ' with BETA badge' : ''}`);
  } catch (err) {
    console.log(`⚠️ Python icon resize fallback: ${err.message}`);
    fs.copyFileSync(iconSrc, logoTarget);
    const mipmaps = ['mipmap-mdpi', 'mipmap-hdpi', 'mipmap-xhdpi', 'mipmap-xxhdpi', 'mipmap-xxxhdpi'];
    for (const mm of mipmaps) {
      const targetDir = path.join(resDir, mm);
      fs.mkdirSync(targetDir, { recursive: true });
      fs.copyFileSync(iconSrc, path.join(targetDir, 'ic_launcher.png'));
    }
  }
}

// 4. Update Android build.gradle applicationId & app label
const buildGradlePath = path.join(rootDir, 'apps', 'mobile', 'android', 'app', 'build.gradle');
if (fs.existsSync(buildGradlePath)) {
  let buildGradle = fs.readFileSync(buildGradlePath, 'utf8');
  buildGradle = buildGradle.replace(
    /applicationId(\s*=\s*|\s+)["'][^"']+["']/,
    `applicationId "${config.applicationId}"`
  );
  fs.writeFileSync(buildGradlePath, buildGradle, 'utf8');
  console.log(`✅ Updated Android applicationId to: ${config.applicationId}`);
}

// 5. Update AndroidManifest.xml label
const manifestPath = path.join(rootDir, 'apps', 'mobile', 'android', 'app', 'src', 'main', 'AndroidManifest.xml');
if (fs.existsSync(manifestPath)) {
  let manifest = fs.readFileSync(manifestPath, 'utf8');
  manifest = manifest.replace(
    /android:label="[^"]*"/,
    `android:label="${config.appName}"`
  );
  fs.writeFileSync(manifestPath, manifest, 'utf8');
  console.log(`✅ Updated AndroidManifest label to: ${config.appName}`);
}

// 6. Generate active_engine.g.dart for compile-time tree-shaking
const engineBridgePath = path.join(rootDir, 'apps', 'mobile', 'lib', 'core', 'engines', 'active_engine.g.dart');
const microFeed = config.microFeed || {};
const engineType = microFeed.engine;

let bridgeContent = '';
if (!microFeed.enabled || !engineType) {
  bridgeContent = `// GENERATED CODE - DO NOT MODIFY BY HAND
// Generated by prepare-instance.js for instance: ${config.instanceId} (DISABLED)

import 'base_feed_engine.dart';

const bool kMicroFeedEnabled = false;

BaseFeedEngine? createActiveFeedEngine() => null;
`;
} else if (engineType === 'scripture') {
  bridgeContent = `// GENERATED CODE - DO NOT MODIFY BY HAND
// Generated by prepare-instance.js for instance: ${config.instanceId}

import 'base_feed_engine.dart';
import '../../features/engines/scripture/scripture_engine.dart';

const bool kMicroFeedEnabled = true;

BaseFeedEngine? createActiveFeedEngine() => ScriptureEngine();
`;
} else if (engineType === 'wftw') {
  bridgeContent = `// GENERATED CODE - DO NOT MODIFY BY HAND
// Generated by prepare-instance.js for instance: ${config.instanceId}

import 'base_feed_engine.dart';
import '../../features/micro_feed/engines/wftw/wftw_feed_engine.dart';

const bool kMicroFeedEnabled = true;

BaseFeedEngine? createActiveFeedEngine() => WftwFeedEngine();
`;
} else {
  bridgeContent = `// GENERATED CODE - DO NOT MODIFY BY HAND
// Generated by prepare-instance.js for instance: ${config.instanceId} (${engineType})

import 'base_feed_engine.dart';

const bool kMicroFeedEnabled = false;

BaseFeedEngine? createActiveFeedEngine() => null;
`;
}

fs.writeFileSync(engineBridgePath, bridgeContent, 'utf8');
console.log(`✅ Generated active_engine.g.dart for [${microFeed.enabled ? engineType : 'DISABLED'}]`);

// 7. Update web/index.html with instance branding
const webIndexPath = path.join(rootDir, 'apps', 'mobile', 'web', 'index.html');
if (fs.existsSync(webIndexPath)) {
  let webIndex = fs.readFileSync(webIndexPath, 'utf8');
  webIndex = webIndex.replace(/<title>[^<]*<\/title>/, `<title>${config.appName}</title>`);
  webIndex = webIndex.replace(
    /<meta name="description" content="[^"]*">/,
    `<meta name="description" content="${config.appName} - High quality Christian videos, shorts, devotions, and words">`
  );
  webIndex = webIndex.replace(
    /<meta name="apple-mobile-web-app-title" content="[^"]*">/,
    `<meta name="apple-mobile-web-app-title" content="${config.appName}">`
  );
  if (config.googleClientId) {
    if (webIndex.includes('google-signin-client_id')) {
      webIndex = webIndex.replace(
        /<meta name="google-signin-client_id" content="[^"]*">/,
        `<meta name="google-signin-client_id" content="${config.googleClientId}">`
      );
    } else {
      webIndex = webIndex.replace(
        '</head>',
        `  <meta name="google-signin-client_id" content="${config.googleClientId}">\n</head>`
      );
    }
  }
  fs.writeFileSync(webIndexPath, webIndex, 'utf8');
  console.log(`✅ Updated web/index.html for: ${config.appName}`);
}

// 8. Update web/manifest.json with instance branding
const webManifestPath = path.join(rootDir, 'apps', 'mobile', 'web', 'manifest.json');
if (fs.existsSync(webManifestPath)) {
  const manifest = JSON.parse(fs.readFileSync(webManifestPath, 'utf8'));
  manifest.name = config.appName;
  manifest.short_name = config.appName;
  manifest.description = `${config.appName} - High quality Christian videos, shorts, devotions, and words`;
  if (config.theme) {
    manifest.background_color = config.theme.lightBackground || '#FFFFFF';
    manifest.theme_color = config.theme.primaryColor || '#0175C2';
  }
  fs.writeFileSync(webManifestPath, JSON.stringify(manifest, null, 4), 'utf8');
  console.log(`✅ Updated web/manifest.json for: ${config.appName}`);
}

console.log(`🎉 Instance preparation complete for ${config.appName}!`);
