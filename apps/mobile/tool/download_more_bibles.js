function namesFromArray(names) {
  const map = {};
  names.forEach((name, i) => {
    const bookNumber = i + 1;
    if (bookNumber >= 1 && bookNumber <= 66) map[String(bookNumber)] = name;
  });
  return map;
}

function fetchJson(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, (res) => {
        if (res.statusCode !== 200) {
          res.resume();
          reject(new Error(`${url} -> ${res.statusCode}`));
          return;
        }
        let data = '';
        res.setEncoding('utf8');
        res.on('data', (c) => (data += c));
        res.on('end', () => resolve(JSON.parse(data)));
      })
      .on('error', reject);
  });
}

async function fetchById(entry) {
  const slugs = (entry.aliases ? [entry.id, ...entry.aliases] : [entry.id]).filter(
    (s, i, arr) => arr.indexOf(s) === i,
  );
  let lastError = null;
  for (const slug of slugs) {
    try {
      return { slug, raw: await fetchJson(`https://api.getbible.net/v2/${slug}.json`) };
    } catch (e) {
      lastError = e;
    }
  }
  throw lastError || new Error('all aliases failed');
}

function convert(raw) {
  // Keep only canonical books 1..66 (drops deuterocanonical/apocrypha that
  // some translations include after the canonical set).
  const books = raw.books
    .filter((b) => b.nr >= 1 && b.nr <= 66)
    .map((b) => ({
      b: b.nr,
      n: b.name,
      ch: b.chapters.map((c) => c.verses.map((v) => v.text)),
    }))
    .sort((a, b) => a.b - b.b);
  return books;
}

function validateStructure(books) {
  if (!Array.isArray(books) || books.length !== 66) {
    return `expected 66 books, got ${books ? books.length : 'none'}`;
  }
  const mismatches = [];
  books.forEach((book, i) => {
    const expectedChapters = KJV_CHAPTERS[i];
    const actual = book.ch.length;
    if (actual !== expectedChapters) {
      mismatches.push(`book#${book.b} (${book.n}): ${actual} ch vs ${expectedChapters} expected`);
    }
  });
  if (mismatches.length === 0) return null;
  return `${mismatches.length} chapter mismatches: ${mismatches.slice(0, 5).join('; ')}`;
}

function toNamesMap(books) {
  const map = {};
  for (const b of books) {
    if (b.nr >= 1 && b.nr <= 66) {
      map[String(b.nr)] = b.name;
    }
  }
  return map;
}

(async () => {
  const biblesDir = path.join(OUT_DIR, 'bibles');
  fs.mkdirSync(biblesDir, { recursive: true });

  const namesOnly = process.argv.includes('--names-only');
  const bookNames = {}; // uppercase-id -> { "1": localized, ... }
  const written = [];

  const namesFile = path.join(OUT_DIR, 'book_names.json');
  if (fs.existsSync(namesFile)) {
    Object.assign(bookNames, JSON.parse(fs.readFileSync(namesFile, 'utf8')));
  }

  for (const t of FETCH) {
    if (namesOnly) break;
    process.stdout.write(`Fetching ${t.id}... `);
    try {
      const { raw } = await fetchById(t);
      const books = convert(raw);
      const problem = validateStructure(books);
      if (problem) {
        console.log(`SKIPPED (${problem})`);
        continue;
      }
      const compact = JSON.stringify({ books });
      const file = path.join(biblesDir, `bible_${t.id}.json`);
      fs.writeFileSync(file, compact);
      bookNames[t.id] = toNamesMap(raw.books);
      const verseCount = books.reduce((s, b) => s + b.ch.reduce((s2, c) => s2 + c.length, 0), 0);
      written.push(`${t.id} (${verseCount} verses, ${compact.length} bytes)`);
      console.log('OK');
    } catch (e) {
      console.log(`SKIPPED (${e.message.replace(/^https?[^ ]+ -> /, '')})`);
    }
  }

  // Harvest localized names for app-sourced bibles (fetch the full payload,
  // extract only the per-book names, write no bible file). Versions that
  // getbible.net does not host fall back to the hand-written LOCALIZED_NAMES.
  for (const id of HARVEST) {
    try {
      const { raw } = await fetchById({ id });
      if (raw && Array.isArray(raw.books) && raw.books.length >= 66) {
        bookNames[id] = toNamesMap(raw.books);
        console.log(`Harvested book names for ${id}`);
        continue;
      }
    } catch (_) {
      // fall through to hand-written table
    }
    if (LOCALIZED_NAMES[id]) {
      bookNames[id] = namesFromArray(LOCALIZED_NAMES[id]);
      console.log(`Used hand-written book names for ${id}`);
    } else {
      console.log(`WARN: no book names for ${id}`);
    }
  }

  if (Object.keys(bookNames).length > 0) {
    fs.writeFileSync(namesFile, JSON.stringify(bookNames, null, 1));
    console.log(`\nbook_names.json -> ${namesFile}`);
    console.log(`  versions: ${Object.keys(bookNames).join(', ')}`);
  }

  console.log('\nWrote bible files:');
  for (const w of written) console.log('  ' + w);
  console.log('\ndone');
})().catch((e) => {
  console.error(e);
  process.exit(1);
});