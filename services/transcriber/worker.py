#!/usr/bin/env python3
"""
transcriber-worker.py — Long-running transcription + AI insights service.

Polls the PrivateTube PostgreSQL database for videos whose
`transcriptionStatus` is `pending`/`processing`, downloads the audio with
yt-dlp, transcribes it locally with faster-whisper (large-v3-turbo, int8 CPU),
writes back the transcript into the `Video.content` column, and then publishes
two assets to the instance's GitHub releases repository (default
`christian_tube` -> `rozariopersonal/Christian-Tube-Releases`):

    transcripts/<videoId>.md     full timestamped transcript
    insights/<videoId>.json      LLM extraction (bible quotes, ideas, truths)
    index.json                   repo manifest

Insights are generated by a local LLM served by Ollama (Qwen2.5 7B Instruct by
default) so no transcript content ever leaves the machine.

Resume behaviour: pending videos are polled. On startup any stale
`processing` rows (from a previously interrupted run) are swept back to
`pending`, so interrupted work still resumes; `completed`/`failed` are skipped
unless `--redo`/`--retry-failed` opt in. One-off runs (`--video-id`,
`--insights-resume`) mark their row `processing`, which the poller ignores, so
manual runs never race the polling loop.

Exit codes: 0 on clean shutdown, 2 no eligible videos in the initial pass.
"""
