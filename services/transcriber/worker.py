def parse_args(argv: list[str]) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Transcribe pending videos and publish transcripts + AI insights to GitHub.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    p.add_argument("--once", action="store_true", help="Process a single batch, then exit (no poll loop).")
    p.add_argument("--retry-failed", action="store_true", help="Also include 'failed' videos (under retry cap).")
    p.add_argument("--redo", action="store_true", help="Re-transcribe / re-publish already completed videos.")
    p.add_argument("--video-id", help="Process a single specific video by YouTube ID.")
    p.add_argument("--no-llm", action="store_true", help="Skip LLM insight extraction (transcript + manifest only).")
    p.add_argument("--insights-resume", action="store_true",
                   help="With --video-id: reuse the stored transcript and run LLM insights only "
                        "(no re-download / re-transcription / transcript re-push).")
    return p.parse_args(argv)


def run(ctx: Config, rows: list[tuple]) -> int:
    db = Database(ctx.database_url)
    trans = build_transcriber(ctx)
    llm: LLM | None = None
    if ctx.no_llm:
        log.warning("  LLM stage skipped (--no-llm).")
    else:
        llm = LLM(ctx.llm_url, ctx.llm_model, ctx.llm_context, ctx.llm_timeout)
        # Ensure the model is present before churning through the backlog.
        llm.ensure_model()
    repo = GitHubRepo(ctx.github_repo, ctx.github_token)

    try:
        first = True
        while True:
            if _interrupted():
                log.info("Shutdown requested; exiting cleanly.")
                return 0
            if first:
                batch = rows
            else:
                batch = db.fetch_eligible(ctx)
            if not batch:
                log.info("Backlog empty; sleeping %ds before re-check...", ctx.poll_interval)
            else:
                log.info("Selected %d video(s):", len(batch))
                for vid, title, ch, _pub in batch:
                    log.info("  - %s | %s (%s)", vid, title, ch)
                for row_tuple in batch:
                    if _interrupted():
                        return 0
                    process_video(db, ctx, trans, llm, repo, row_tuple)
            first = False
            if ctx.once:
                return 0 if batch else 2
            deadline = time.time() + ctx.poll_interval
            while not _interrupted() and time.time() < deadline:
                time.sleep(5)
    finally:
        db.close()


def main(argv: list[str] | None = None) -> int:
    global _split_to_epoch
    args = parse_args(argv or sys.argv[1:])

    def _handle(signum, _frame):
        global _split_to_epoch
        log.info("Signal %s received; finishing current video then exiting.", signum)
        _split_to_epoch = time.time() + 30

    signal.signal(signal.SIGTERM, _handle)
    signal.signal(signal.SIGINT, _handle)

    ctx = load_config(args)
    if ctx.video_id:
        ctx.once = True
    ctx.work_dir.mkdir(parents=True, exist_ok=True)
    ctx.whisper_model_dir.mkdir(parents=True, exist_ok=True)

    db = Database(ctx.database_url)
    db.release_stale_processing()
    try:
        if ctx.video_id:
            row = db.fetch_one(ctx.video_id)
            rows = [row] if row else []
            if not rows:
                log.error("Video %s not found in database.", ctx.video_id)
                return 1
        else:
            rows = db.fetch_eligible(ctx)
    finally:
        db.close()

    return run(ctx, rows)


if __name__ == "__main__":
    sys.exit(main())