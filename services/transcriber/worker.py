# Insight extraction prompt
# --------------------------------------------------------------------------- #
SYSTEM_PROMPT = """You are a meticulous Bible scholar analysing a sermon transcript.
Extract, without inventing anything that is not actually in the transcript:

1. "bibleQuotes": every Scripture verse the preacher quoted or clearly paraphrased.
   Fields: "quote" (the exact words as spoken, keep short), "reference" (best-guess
   book chapter:verse, e.g. "Romans 3:23"), "confidence" (high|medium|low), and
   "context" (one short sentence about where it appears).
2. "ideas": key theological/doctrinal points the preacher made.
3. "truths": standalone spiritual principles or life applications taught.
4. "themes": 3-8 broad themes of the sermon.
5. "keywords": up to 10 single terms for search.
6. "summary": a 4-6 sentence summary of the whole transcript.

Rules:
- Only quote Scripture that actually appears (or is explicitly cited) in the text.
- Never fabricate references; if unsure, still give a best-guess reference but mark
  confidence "low".
- Respond ONLY with valid JSON matching this exact shape:
{"bibleQuotes":[{"quote":"...","reference":"...","confidence":"high|medium|low","context":"..."}],"ideas":["..."],"truths":["..."],"themes":["..."],"keywords":["..."],"summary":"..."}"""


# --------------------------------------------------------------------------- #
# Pipeline helpers
# --------------------------------------------------------------------------- #
def _estimate_tokens(text: str) -> int:
    return int(len(text) / 3.7)  # rough English token estimate


def _chunk_transcript(text: str, budget_chars: int) -> list[str]:
    if len(text) <= budget_chars:
        return [text]
    lines = text.split("\n")
    chunks: list[str] = []
    cur: list[str] = []
    cur_len = 0
    for line in lines:
        if cur_len + len(line) + 1 > budget_chars and cur:
            chunks.append("\n".join(cur))
            cur, cur_len = [], 0
        cur.append(line)
        cur_len += len(line) + 1
    if cur:
        chunks.append("\n".join(cur))
    return chunks


def _dedupe(items: list, key) -> list:
    seen: set = set()
    out = []
    for it in items:
        k = key(it)
        if k in seen:
            continue
        seen.add(k)
        out.append(it)
    return out


def extract_insights(llm: LLM, transcript: str) -> dict:
    reserve = 4000
    avail = llm.context - reserve
    budget_chars = min(max(4000, int(avail * 3.7)), 25000)
    chunks = _chunk_transcript(transcript, budget_chars)
    parts = []
    total = len(chunks)
    for i, chunk in enumerate(chunks, start=1):
        meta = "" if total == 1 else (
            f"\n\n[NOTE: this is part {i} of {total}; extract everything you find in this part.]"
        )
        parts.append(
            llm.generate_json(
                SYSTEM_PROMPT,
                f"TRANSCRIPT:\n{chunk}{meta}\n\nReturn the JSON now.",
            )
        )
        log.info("  extracted part %d/%d", i, total)

    if len(parts) == 1:
        return parts[0]

    quotes = [q for p in parts for q in p.get("bibleQuotes", [])]
    quotes = _dedupe(quotes, lambda q: (q.get("reference", ""), q.get("quote", "").lower()))
    return {
        "bibleQuotes": quotes,
        "ideas": _dedupe([i for p in parts for i in p.get("ideas", [])], str.lower),
        "truths": _dedupe([t for p in parts for t in p.get("truths", [])], str.lower),
        "themes": _dedupe([t for p in parts for t in p.get("themes", [])], str.lower),
        "keywords": _dedupe([k for p in parts for k in p.get("keywords", [])], str.lower),
        "summary": " ".join(p.get("summary", "") for p in parts if p.get("summary")),
    }


def _build_manifest(repo: GitHubRepo) -> list[dict]:
    raw = repo.read_text_or_none("index.json")
    if raw is None:
        return []
    import json  # noqa: E402

    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        log.warning("  index.json in repo was invalid JSON; starting fresh.")
        return []
    return data if isinstance(data, list) else []


def update_manifest(repo: GitHubRepo, entry: dict) -> None:
    entries = [e for e in _build_manifest(repo) if e.get("videoId") != entry["videoId"]]
    entries.append(entry)
    entries.sort(key=lambda e: e.get("publishedAt", ""), reverse=True)
    import json  # noqa: E402

    repo.upsert("index.json", json.dumps(entries, indent=2, ensure_ascii=False), f"manifest: {entry['videoId']}")


def _interrupted() -> bool:
    return _split_to_epoch is not None and time.time() >= _split_to_epoch


# --------------------------------------------------------------------------- #
# Per-video processing
# --------------------------------------------------------------------------- #
def process_video(db: Database, cfg: Config, trans: Transcriber, llm: LLM,
                  repo: GitHubRepo, row: tuple) -> None:
    video_id, title, channel, published_at = row
    mark = f"-> {video_id} | {title} ({channel})"
    log.info(">> Processing %s", mark)
    try:
        db.mark_processing(video_id)
        transcript: str | None = None
        if cfg.insights_resume:
            got = db.fetch_content(video_id)
            if got and got[0]:
                transcript = got[0]
                log.info("  resuming: reusing existing transcript from DB (%d chars)", len(transcript))
        if transcript is None:
            with tempfile.TemporaryDirectory(prefix="tw_", dir=str(cfg.work_dir)) as tmp:
                wav = download_audio(video_id, Path(tmp))
                db.mark_progress(video_id, 40)
                transcript = trans.transcribe(wav)
                db.mark_progress(video_id, 70)
                log.info("  transcript: %d chars", len(transcript))

            db.mark_completed(video_id, transcript)
            log.info("  saved transcript to DB (status=completed)")

            # 1) Transcript -> transcripts/<id>.md
            md = f"# {title}\n\n- Video: https://www.youtube.com/watch?v={video_id}\n- Channel: {channel}\n\n---\n\n{transcript}\n"
            url = repo.upsert(
                f"transcripts/{video_id}.md",
                md,
                f"Add transcript {video_id}",
            )
            log.info("  pushed transcript: %s", url)
        else:
            log.info("  transcript already published; skipping re-push")
            # Insights-only resume: restore the row to 'completed' (idempotent —
            # content is unchanged, so mark_completed just clears the
            # manual 'processing' flag now that the run succeeded).
            db.mark_completed(video_id, transcript)

        # 2) Insights via local LLM -> insights/<id>.json
        db.mark_progress(video_id, 80)
        if llm is not None:
            payload = extract_insights(llm, transcript)
            import json  # noqa: E402

            doc = {
                "videoId": video_id,
                "title": title,
                "channel": channel,
                "publishedAt": published_at.isoformat() if hasattr(published_at, "isoformat") else str(published_at),
                "llm": {"model": cfg.llm_model, "generatedAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())},
                "insights": payload,
            }
            url = repo.upsert(
                f"insights/{video_id}.json",
                json.dumps(doc, indent=2, ensure_ascii=False),
                f"Add insights {video_id}",
            )
            log.info("  pushed insights: %s", url)

        # 3) Manifest
        update_manifest(repo, {
            "videoId": video_id,
            "title": title,
            "channel": channel,
            "publishedAt": getattr(published_at, "isoformat", lambda: str(published_at))(),
            "transcript": f"transcripts/{video_id}.md",
            "insights": f"insights/{video_id}.json",
            "updatedAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        })
        db.mark_progress(video_id, 100)
        log.info(">> Done: %s", video_id)
    except Exception as e:  # noqa: BLE001
        log.error(">> Failed %s: %s", video_id, e)
        db.mark_failed(video_id, str(e))


